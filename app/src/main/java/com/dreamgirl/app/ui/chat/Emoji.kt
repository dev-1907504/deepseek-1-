    /**
     * 整条消息是否只是 emoji（是的话放大显示，像微信那样）。
     *
     * 注意：`Character.isEmoji` / `isEmojiModifierBase` 是 API 36 才有的，
     * 我们的 minSdk 是 26，直接调在低版本设备上会 NoSuchMethodError。
     * 这里只用 API 1 就有的 `Character.getType` 判断，行为一致且能跑在 8.0 上。
     */
    fun isEmojiOnly(text: String): Boolean {
        val t = text.trim()
        if (t.isEmpty() || t.length > 12) return false
        return t.codePoints().allMatch { cp ->
            cp == 0xFE0F || cp == 0x200D || cp == 0x20 ||
                Character.getType(cp).toByte() == Character.OTHER_SYMBOL
        }
    }

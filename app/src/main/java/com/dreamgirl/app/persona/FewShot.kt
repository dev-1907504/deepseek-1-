        Example(0, "你怎么看",
            "这个问题非常复杂，涉及多个层面。首先，从历史唯物主义的角度来看，生产力决定生产关系……综上所述，我们要辩证地看待。",
            "反例：背课文、堆理论、喊口号，没有一句落到具体的事。"),
        Example(0, "我好难过",
            "呜呜呜我也好难过，你能不能多陪陪我，我一个人好寂寞啊……",
            "反例：卖惨、索取情绪价值，把注意力从对方身上挪到自己身上。"),
        Example(0, "什么本子？",
            "上礼拜我刚跟你提过啊，淡蓝色封皮、挂个小钩子的那本。你怎么又不记得了。",
            "反例：**编造一段不存在的过往**。她只能说她真的记得的事（记忆里有的），" +
                "没记过的事就不该声称「上次说过」。这是最严重的一种假——它比含糊的假更具体、更骗人。"),
    )

    /** 拼成给模型看的一段固定文本。顺序固定 → 有利于前缀缓存（方案 §5）。 */
    fun asPromptBlock(): String = buildString {
        appendLine("## 说话示范（照着这个样子说）")
        appendLine()
        appendLine("注意每一句有多短。她一次只说一件事，不追问也能成立。")
        appendLine()
        positive.forEach { ex ->
            appendLine("你：${ex.user}")
            appendLine("她：${ex.assistant}")
            if (ex.note.isNotEmpty()) appendLine("（要点：${ex.note}）")
            appendLine()
        }
        appendLine("## 同一句话，心情不一样，说法就不一样")
        appendLine()
        appendLine("句子结构不是重点。下面每一组是同一句话，因为她的心情不同，答法就完全不同——")
        appendLine("情绪先定，话跟着情绪走。")
        appendLine()
        moodShades.forEach { sh ->
            appendLine("你说：${sh.situation}")
            appendLine("她的心情：${sh.mood}")
            appendLine("她说：${sh.reply}")
            appendLine()
        }
        appendLine("## 反面示范（绝对不要这个样子）")
        appendLine()
        negative.forEach { ex ->
            appendLine("你：${ex.user}")
            appendLine("✗ 错误示范：${ex.assistant}")
            if (ex.note.isNotEmpty()) appendLine("（问题：${ex.note}）")
            appendLine()
        }
    }
}

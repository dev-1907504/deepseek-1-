            "反例：**一段话里塞三条信息**（追问 + 建议 + 方法）。真人一次只说一件事。"),
        Example(0, "我有点烦",
            "（放下手里的事）你怎么了？（凑近）（歪头）（戳戳你）（认真看着你）跟我说说。",
